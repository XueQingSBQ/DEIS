export function findRegionByCode(code: string): RegionCatalogItem | undefined {
  return regionCatalog.find((item) => item.code === code);
}

export function listProvinceCities(provinceCode: string): RegionCatalogItem[] {
  const provincePrefix = (provinceCode || "").slice(0, 2);
  const matches = regionCatalog.filter((item) => item.kind === "CITY" && item.code.slice(0, 2) === provincePrefix);
  if (matches.length > 0) {
    return matches;
  }
  const province = findRegionByCode(provinceCode);
  return province ? [province] : [];
}
